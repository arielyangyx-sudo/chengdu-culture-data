  function readStore() {
    try {
      var raw = localStorage.getItem(STORE_KEY);
      if (!raw) return { site: null, banners: null, news: null, notices: null, cases: null, projects: null, businesses: null, stats: null, about: null };
      return JSON.parse(raw);
    } catch (e) {
      return {};
    }
  }

  /**
   * 深合并：管理端数据覆盖默认数据（数组整体替换）
   */
  function merge() {
    var override = readStore();
    var result = JSON.parse(JSON.stringify(DEFAULTS));
    ['site', 'banners', 'stats', 'functions', 'businesses', 'cases', 'projects', 'news', 'notices', 'about'].forEach(function (k) {
      if (override[k] !== undefined && override[k] !== null) result[k] = override[k];
    });
    // 新闻/公告按日期倒序
    ['news', 'notices'].forEach(function (k) {
      if (Array.isArray(result[k])) {
        result[k].sort(function (a, b) { return String(b.date || '').localeCompare(String(a.date || '')); });
      }
    });
    return result;
  }

  global.CDBG = {
    DEFAULTS: DEFAULTS,
    STORE_KEY: STORE_KEY,
    data: function () { return merge(); },
    save: function (data) { localStorage.setItem(STORE_KEY, JSON.stringify(data)); },
    reset: function () { localStorage.removeItem(STORE_KEY); }
  };
